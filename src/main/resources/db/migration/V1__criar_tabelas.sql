CREATE TABLE colaboradores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(200) NOT NULL CHECK (length(trim(nome)) > 0),
    salario_base NUMERIC NOT NULL CHECK (salario_base >= 0),
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN ('PADRAO', 'COMISSIONADO', 'PRODUCAO')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE remuneracoes_comissao (
    colaborador_id BIGINT PRIMARY KEY
        REFERENCES colaboradores(id) ON DELETE RESTRICT,
    valor_vendas NUMERIC NOT NULL CHECK (valor_vendas >= 0),
    percentual_comissao NUMERIC NOT NULL
        CHECK (percentual_comissao >= 0)
);

CREATE TABLE remuneracoes_producao (
    colaborador_id BIGINT PRIMARY KEY
        REFERENCES colaboradores(id) ON DELETE RESTRICT,
    quantidade_produzida NUMERIC NOT NULL
        CHECK (quantidade_produzida >= 0),
    valor_por_unidade NUMERIC NOT NULL
        CHECK (valor_por_unidade >= 0)
);